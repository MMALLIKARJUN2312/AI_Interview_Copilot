import type {
  FeedbackResponse,
  QuestionWithAnswer,
  RoadmapResponse,
  SessionSummary,
} from "@/lib/types";

interface InterviewReportData {
  session: SessionSummary;
  questions: QuestionWithAnswer[];
  feedback: FeedbackResponse | null;
  roadmap: RoadmapResponse | null;
}

function formatTimestamp(
  value: string | null,
): string {
  if (!value) {
    return "Not completed";
  }

  const parsed = new Date(value);

  if (Number.isNaN(parsed.getTime())) {
    return value;
  }

  return parsed.toISOString();
}

function formatLabel(value: string): string {
  return value
    .replaceAll("_", " ")
    .replace(/\b\w/g, (character) =>
      character.toUpperCase(),
    );
}

function appendList(
  lines: string[],
  heading: string,
  items: string[],
): void {
  lines.push(`### ${heading}`, "");

  if (items.length === 0) {
    lines.push("- None recorded", "");
    return;
  }

  lines.push(
    ...items.map((item) => `- ${item}`),
    "",
  );
}

export function buildInterviewReport({
  session,
  questions,
  feedback,
  roadmap,
}: InterviewReportData): string {
  const lines: string[] = [
    "# AI Interview Copilot Report",
    "",
    `## ${session.target_role}`,
    "",
    `- Session ID: ${session.id}`,
    `- Status: ${formatLabel(session.status)}`,
    `- Questions answered: ${session.current_index}/${session.total_questions}`,
    `- Created: ${formatTimestamp(session.created_at)}`,
    `- Completed: ${formatTimestamp(session.completed_at)}`,
    `- Overall score: ${
      session.overall_score === null
        ? "Not available"
        : `${session.overall_score}/100`
    }`,
    "",
  ];

  if (feedback) {
    lines.push(
      "## Overall performance",
      "",
      `**Score:** ${feedback.overall_score}/100`,
      "",
      feedback.summary,
      "",
    );

    appendList(
      lines,
      "Strengths",
      feedback.strengths,
    );

    appendList(
      lines,
      "Weaknesses",
      feedback.weaknesses,
    );

    lines.push(
      "### Recommendation",
      "",
      feedback.recommendation,
      "",
    );
  }

  const answeredQuestions = questions.filter(
    (question) => question.answer !== null,
  );

  if (answeredQuestions.length > 0) {
    lines.push(
      "## Question-by-question review",
      "",
    );

    answeredQuestions.forEach((question) => {
      const answer = question.answer;

      if (!answer) {
        return;
      }

      lines.push(
        `### Question ${question.order_index + 1}`,
        "",
        `- Round: ${formatLabel(question.round_type)}`,
        `- Difficulty: ${formatLabel(question.difficulty)}`,
        `- Score: ${answer.score}/100`,
        "",
        "**Question**",
        "",
        question.question_text,
        "",
        "**Evaluation**",
        "",
        answer.feedback,
        "",
      );

      if (answer.total_test_count !== null) {
        lines.push(
          `**Test cases:** ${
            answer.passed_test_count ?? 0
          }/${answer.total_test_count} passed`,
          "",
        );
      }

      if (
        answer.execution_results &&
        answer.execution_results.length > 0
      ) {
        lines.push(
          "**Execution results**",
          "",
          ...answer.execution_results.map(
            (result, index) =>
              `- Test ${index + 1}: ${
                result.passed ? "Passed" : "Failed"
              }`,
          ),
          "",
        );
      }

      appendList(
        lines,
        "Strengths",
        answer.strengths,
      );

      appendList(
        lines,
        "Areas to improve",
        answer.improvements,
      );
    });
  }

  if (roadmap && roadmap.items.length > 0) {
    lines.push(
      "## Learning roadmap",
      "",
    );

    roadmap.items.forEach((item, index) => {
      lines.push(
        `### ${index + 1}. ${item.topic}`,
        "",
        `**Priority:** ${formatLabel(item.priority)}`,
        "",
        item.description,
        "",
      );

      appendList(
        lines,
        "Resources",
        item.resources,
      );
    });
  }

  lines.push(
    "---",
    "",
    "Generated by AI Interview Copilot.",
    "",
  );

  return lines.join("\n");
}

export function createInterviewReportFilename(
  session: SessionSummary,
): string {
  const roleSlug = session.target_role
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  return [
    "interview",
    roleSlug || "report",
    session.id,
  ].join("-") + ".md";
}