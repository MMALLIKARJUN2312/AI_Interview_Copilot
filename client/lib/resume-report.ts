import type {
  ResumeAnalysisResponse,
  ResumeSummary,
} from "@/lib/types";

interface ResumeReportData {
  resume: ResumeSummary;
  analysis: ResumeAnalysisResponse;
}

function formatTimestamp(value: string): string {
  const parsed = new Date(value);

  if (Number.isNaN(parsed.getTime())) {
    return value;
  }

  return parsed.toISOString();
}

function appendList(
  lines: string[],
  heading: string,
  items: string[],
): void {
  lines.push(`## ${heading}`, "");

  if (items.length === 0) {
    lines.push("- None recorded", "");
    return;
  }

  lines.push(
    ...items.map((item) => `- ${item}`),
    "",
  );
}

export function buildResumeReport({
  resume,
  analysis,
}: ResumeReportData): string {
  const lines: string[] = [
    "# AI Interview Copilot Resume Analysis",
    "",
    `## ${analysis.target_role}`,
    "",
    `- Resume: ${resume.original_filename}`,
    `- Resume ID: ${resume.id}`,
    `- Analysis ID: ${analysis.analysis_id}`,
    `- Status: ${resume.status}`,
    `- Uploaded: ${formatTimestamp(resume.created_at)}`,
    `- ATS score: ${analysis.ats_score}/100`,
    "",
    "## ATS assessment",
    "",
    `This resume received an ATS compatibility score of **${analysis.ats_score}/100** for the **${analysis.target_role}** role.`,
    "",
  ];

  appendList(
    lines,
    "Strengths",
    analysis.strengths,
  );

  appendList(
    lines,
    "Weaknesses",
    analysis.weaknesses,
  );

  appendList(
    lines,
    "Recommended improvements",
    analysis.suggestions,
  );

  lines.push(
    "---",
    "",
    "Generated by AI Interview Copilot.",
    "",
    "This automated analysis should be used as guidance and does not guarantee an interview or hiring outcome.",
    "",
  );

  return lines.join("\n");
}

export function createResumeReportFilename(
  resume: ResumeSummary,
): string {
  const roleSlug = resume.target_role
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  const resumeSlug = resume.original_filename
    .replace(/\.pdf$/i, "")
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  return [
    "resume-analysis",
    roleSlug || resumeSlug || "report",
    resume.id,
  ].join("-") + ".md";
}